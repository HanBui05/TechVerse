import { expect, it } from 'vitest'
import { dashboardText, formatCount, formatMoney } from './dashboardI18n'

it('formats counts and VND amounts in vi and en and returns "—" when missing', () => {
  expect(formatCount(null, 'vi')).toBe('—')
  expect(formatCount(undefined, 'en')).toBe('—')
  expect(formatCount(Number.NaN, 'vi')).toBe('—')
  expect(formatCount(0, 'vi')).toBe('0')
  expect(formatCount(1248, 'vi')).toBe('1.248')
  expect(formatCount(1248, 'en')).toBe('1,248')

  expect(formatMoney(null, 'vi')).toBe('—')
  expect(formatMoney(undefined, 'en')).toBe('—')
  expect(formatMoney(0, 'vi')).toMatch(/0\s*₫/)
  expect(formatMoney(45600000, 'vi')).toMatch(/45\.600\.000\s*₫/)
  expect(formatMoney(45600000, 'en')).toMatch(/₫45,600,000|45,600,000\s*₫/)
})

